// Generate src/api/schema.d.ts from the backend's OpenAPI document (backend/scripts/export_openapi.py).
// Run after a backend change to the API: `npm run gen:api`. CI regenerates the file and fails when it
// differs from the committed one, so the types always match the server.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const ownerWebDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const backendDir = resolve(ownerWebDir, "../backend");
const output = resolve(ownerWebDir, "src/api/schema.d.ts");

const document = execFileSync("uv", ["run", "--frozen", "python", "scripts/export_openapi.py"], {
  cwd: backendDir,
  encoding: "utf-8",
  maxBuffer: 64 * 1024 * 1024,
  stdio: ["ignore", "pipe", "inherit"],
});

const header = [
  "// Generated by `npm run gen:api` from the backend's OpenAPI document. Do not edit by hand.",
  "",
  "",
].join("\n");
const ast = await openapiTS(JSON.parse(document));
writeFileSync(output, header + astToString(ast));
console.log(`Wrote ${output}`);
