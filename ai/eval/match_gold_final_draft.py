def main() -> None:
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    keys = {p["key"] for p in catalog["products"]}
    labels = json.loads(LABELS.read_text(encoding="utf-8"))
    photos, missing = [], []
    for p in labels["photos"]:
        items = []
        for i in p["items"]:
            g = GOLD.get(i["raw_name"])
            if g is None:
                missing.append(i["raw_name"])
                continue
            items.append({"raw_name": i["raw_name"], "unit": i["unit"], "pour_ml": i["pour_ml"], "gold": g})
        photos.append({"photo_id": p["photo_id"], "bar": p["bar"], "split": "final", "items": items})
    if missing:
        raise SystemExit(f"no gold for: {sorted(set(missing))}")
    unused = set(GOLD) - {i["raw_name"] for p in labels["photos"] for i in p["items"]}
    if unused:
        raise SystemExit(f"gold names not in labels: {sorted(unused)}")
    for g in GOLD.values():
        if g.startswith("new:"):
            assert g[4:] in NEW, g
        elif g not in (U, NW):
            assert g in keys, g
    clash = set(NEW) & keys
    assert not clash, clash
    out = {
        "version": "match_gold_final_v1",
        "created": "2026-10-14",
        "split": {"final": ["수이", "오드비"]},
        "labeling": "Claude draft from labels_final_v1 names and catalog_v2_draft (no extraction/matching output); "
                    "human review of `review` pending",
        "catalog": "ai/catalog/catalog_v2_draft.json (keys); new: products are added to catalog v2 in step 3",
        "review": REVIEW,
        "new_products": {k: {"display_name": d, "brand": br, "age_years": a, "edition_name": e}
                         for k, (d, br, a, e) in NEW.items()},
        "photos": photos,
    }
    OUT.write_bytes((json.dumps(out, ensure_ascii=False, indent=1) + "\n").encode("utf-8"))
    lines = [i for p in photos for i in p["items"]]
    kinds = {"catalog": 0, "new": 0, "unknown": 0, "non_whisky": 0}
    for i in lines:
        g = i["gold"]
        kinds["new" if g.startswith("new:") else g if g in (U, NW) else "catalog"] += 1
    print(f"wrote {OUT.relative_to(REPO_ROOT)}: {len(photos)} photos, {len(lines)} lines, "
          f"{len(NEW)} new products, {kinds}")


if __name__ == "__main__":
    main()
